#!/usr/bin/env python3
"""Generate rust/src/crt_tables.rs from faest-arch-opt's generated crt_constants_128f.cpp/hpp.

Usage: gen_crt.py <build>/subprojects/faest-arch-opt > rust/src/crt_tables.rs
"""
import re
import sys

d = sys.argv[1]
cpp = open(f"{d}/crt_constants_128f.cpp").read()
hpp = open(f"{d}/crt_constants_128f.hpp").read()


def table(src, name):
    m = re.search(r"CRT_CONSTANTS_128_17_120::" + name + r" = \{\{(.*?)\}\};", src, re.S)
    rows = re.findall(r"\{([^{}]*)\}", m.group(1))
    return [[int(x, 0) for x in r.replace("\n", " ").split(",") if x.strip()] for r in rows]


def flat(src, name):
    m = re.search(r"CRT_CONSTANTS_128_17_120::" + name + r" = \{(.*?)\};", src, re.S)
    return [int(x, 0) for x in m.group(1).split(",") if x.strip()]


n_mult = int(re.search(r"N_MULT = (\d+);", hpp).group(1))
rows = {
    "W_CRT": table(cpp, "W_CRT_LIFT_ROW_TAB"),
    "W_TREE": table(cpp, "W_TREE_LIFT_ROW_TAB"),
    "W_GATE": table(cpp, "W_GATE_LIFT_ROW_TAB"),
    "F": table(cpp, "F_LIFT_ROW_TAB"),
    "G": table(cpp, "G_LIFT_ROW_TAB"),
}
idx = {
    "W_CRT": table(cpp, "W_CRT_LIFT_COLUMNS_INDEX_TAB"),
    "W_GATE": table(cpp, "W_GATE_LIFT_COLUMNS_INDEX_TAB"),
    "G": table(cpp, "G_LIFT_COLUMNS_INDEX_TAB"),
}

# Check that the column index tables are derived from the row tables as we assume.
for name, tab in idx.items():
    r = rows[name]
    for c, chunk in enumerate(tab):
        for j, x in enumerate(chunk):
            want = 0
            for t in range(4):
                i = 4 * c + t
                if i < len(r) and (r[i][j // 64] >> (j % 64)) & 1:
                    want |= 1 << t
            assert want == x, (name, c, j)

m_i = flat(hpp, "M_i")
div = flat(hpp, "DIV_X64_by_M_i")
m_tree = flat(hpp, "M_TREE")

out = sys.stdout
out.write("// Generated by tools/gen_crt.py from faest-arch-opt's crt_constants_128f. Do not edit.\n\n")
out.write(f"pub const N_MULT: usize = {n_mult};\n\n")
out.write("pub const M_I: [u64; 17] = [%s];\n" % ", ".join(hex(x) for x in m_i))
out.write("pub const DIV_X64_BY_M_I: [u64; 17] = [%s];\n" % ", ".join(hex(x) for x in div))
out.write("pub const M_TREE: [u8; 16] = [%s];\n\n" % ", ".join(hex(x) for x in m_tree))
for name, r in rows.items():
    w = len(r[0])
    out.write(f"pub static {name}_ROWS: [[u64; {w}]; {len(r)}] = [\n")
    for row in r:
        out.write("    [%s],\n" % ", ".join("0x%016x" % x for x in row))
    out.write("];\n\n")
