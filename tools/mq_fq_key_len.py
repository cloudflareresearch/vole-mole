#!/usr/bin/env python3
"""Generate the key length table of the MQ PRG over F_q, q = 3329 (src/voleith_fq/mq_key_len.hpp).

The PRG stretches a key K in F_q^n into N outputs in F_q, each a random quadratic form in K. For
each key length n (even), this script estimates the largest number of outputs N for which solving
G(K) = y (n unknowns, N equations over F_q) still costs at least 2^SECURITY_BITS.

As tools/mq_key_bits.py, the estimate is deliberately simple and should be checked against the
CryptographicEstimators library (MQEstimator) before relying on it:

  - The system is assumed semi-regular. Over a large field there are no field equations, so its
    degree of regularity D_reg is the index of the first non-positive coefficient of the Hilbert
    series (1 - z^2)^N / (1 - z)^n (Bardet, Faugere, Salvy).
  - Solving costs (number of monomials of degree <= D_reg)^OMEGA, i.e., binom(n + D_reg, D_reg)^OMEGA,
    as for XL with sparse linear algebra (OMEGA = 2), minimized over the hybrid approach of
    guessing g variables first, which multiplies the cost by q^g. (For q = 3329, guessing never
    pays off.)

The PRG trick for the ML-KEM PoP only needs G(K) to hide s = e + G(K), where s is short; that is
at least as hard as distinguishing G(K) from uniform given all of G(K), so this is conservative in
that respect.

Usage: tools/mq_fq_key_len.py > src/voleith_fq/mq_key_len.hpp
"""

import sys
from math import comb, log2

Q = 3329
SECURITY_BITS = 128
OMEGA = 2
MIN_KEY_LEN = 16
MAX_KEY_LEN = 320
KEY_LEN_STEP = 2
MAX_GUESSED = 4


def degree_of_regularity(n, m):
    """Index of the first non-positive coefficient of (1 - z^2)^m / (1 - z)^n, or None."""
    for d in range(4 * n + 4):
        coeff = sum(
            (-1) ** k * comb(m, k) * comb(n - 1 + d - 2 * k, d - 2 * k) for k in range(d // 2 + 1)
        )
        if coeff <= 0:
            return d
    return None


def log2_cost(n, m):
    """log2 of the estimated cost of solving m random quadratic equations in n variables."""
    best = None
    for g in range(min(MAX_GUESSED, n - 1) + 1):
        d = degree_of_regularity(n - g, m)
        if d is None:
            continue
        cost = g * log2(Q) + OMEGA * log2(comb(n - g + d, d))
        best = cost if best is None else min(best, cost)
    return best


def max_outputs(n):
    """The largest m for which log2_cost(n, m) >= SECURITY_BITS, or 0 if there is none."""
    if log2_cost(n, n) < SECURITY_BITS:
        return 0
    lo, hi = n, n + comb(n + 1, 2)  # beyond hi, linearization breaks the system
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if log2_cost(n, mid) >= SECURITY_BITS:
            lo = mid
        else:
            hi = mid
    return lo


def main():
    entries = []
    best = 0
    for n in range(MIN_KEY_LEN, MAX_KEY_LEN + 1, KEY_LEN_STEP):
        m = max_outputs(n)
        print(f"n = {n}: N <= {m}", file=sys.stderr)
        # D_reg is a step function, so max_outputs isn't quite monotone; keep the running max.
        if m > best:
            best = m
            entries.append((n, m))

    print(f"""// Generated by tools/mq_fq_key_len.py; do not edit.
//
// For each key length n of the MQ PRG over F_q, the largest number of outputs N for which the
// estimated cost of solving N random quadratic equations in n variables over F_3329 is at least
// 2^{SECURITY_BITS} (semi-regular D_reg, XL with omega = {OMEGA}, hybrid guessing). See
// tools/mq_fq_key_len.py for the caveats.

#ifndef VOLE_MOLE_VOLEITH_FQ_MQ_KEY_LEN_HPP
#define VOLE_MOLE_VOLEITH_FQ_MQ_KEY_LEN_HPP

#include <array>
#include <cstddef>

namespace vole_mole::voleith_fq::detail {{

struct MqKeyLenEntry {{
    size_t key_len;
    size_t max_outputs;
}};

constexpr std::array MQ_KEY_LEN_TABLE = {{""")
    for n, m in entries:
        print(f"    MqKeyLenEntry{{{n}, {m}}},")
    print("""};

} // namespace vole_mole::voleith_fq::detail

#endif""")


if __name__ == "__main__":
    main()
