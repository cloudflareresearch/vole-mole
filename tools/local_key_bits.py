#!/usr/bin/env python3
"""Generate the key length tables of the local PRG (src/mq/local_key_bits.hpp).

The local PRG (see src/mq/local.hpp) stretches a key K of n bits into N output bits, each of the
form

  y_i = K_{l_1} + ... + K_{l_L} + K_{a_1} K_{b_1} + ... + K_{a_q} K_{b_q}

for public, pseudorandom, distinct indices. For q = 1 this is Goldreich's PRG with the predicate
XOR_L-AND_2. For each q in ANDS and each key length n (a multiple of 8), this script estimates the
largest N for which recovering K from G(K) still costs at least 2^SECURITY_BITS against:

  - Guess and determine (Couteau, Dupin, Meaux, Rossi, Rotella, Asiacrypt 2018, Section 4): guess
    g key bits; an output becomes linear in the rest if each of its q products contains a guessed
    bit, which happens with probability p = (1 - (1 - g / n)^2)^q. Once N p >= n - g outputs are
    linear, solve them. The cost is 2^g (n - g)^2, minimized over g. (Choosing the most frequent
    bits instead of random ones helps the attacker a little; we don't account for that.)

  - Algebraic attacks: we assume the system is no harder to solve than a dense random quadratic
    system of the same size, i.e., we also require the estimate of tools/mq_key_bits.py. This is a
    heuristic floor: sparse systems may well be easier for Groebner basis / XL algorithms, which
    Couteau et al. analyze separately (and find to be the binding attack for small q and large
    stretch).

This is a first, rough estimate for performance experiments, NOT a security analysis. In
particular it ignores distinguishing attacks that don't recover the key (linear tests on small sets
of outputs, which the linear terms are meant to defeat) and the attacks of Couteau et al. and
later work (e.g., Unal, "Worst-case subexponential attacks on PRGs of constant degree or constant
locality", Eurocrypt 2023) that are specific to local PRGs. The parameters must be checked against
that literature before relying on them.

Usage: tools/local_key_bits.py | clang-format --assume-filename=src/mq/local_key_bits.hpp \
  > src/mq/local_key_bits.hpp
"""

import sys
from math import log2

import mq_key_bits

SECURITY_BITS = 128
ANDS = (1, 2, 4)
MIN_KEY_BITS = 128
MAX_KEY_BITS = 1536
KEY_BITS_STEP = 8


def log2_cost_guess_and_determine(n, m, q):
    """log2 of the cost of the guess-and-determine attack on m outputs with n key bits."""
    for g in range(1, n):
        p = (1 - (1 - g / n) ** 2) ** q
        if m * p >= n - g:
            return g + 2 * log2(n - g)
    return n


def max_outputs(n, q):
    """The largest m for which both estimates are at least SECURITY_BITS, or 0 if there is none."""
    if log2_cost_guess_and_determine(n, n, q) < SECURITY_BITS:
        return 0
    lo, hi = n, 64 * n
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if log2_cost_guess_and_determine(n, mid, q) >= SECURITY_BITS:
            lo = mid
        else:
            hi = mid
    # The dense MQ estimate decreases with m, too.
    if mq_key_bits.log2_cost(n, lo) >= SECURITY_BITS:
        return lo
    if mq_key_bits.log2_cost(n, n) < SECURITY_BITS:
        return 0
    lo2, hi2 = n, lo
    while hi2 - lo2 > 1:
        mid = (lo2 + hi2) // 2
        if mq_key_bits.log2_cost(n, mid) >= SECURITY_BITS:
            lo2 = mid
        else:
            hi2 = mid
    return lo2


def main():
    tables = {}
    for q in ANDS:
        entries = []
        for n in range(MIN_KEY_BITS, MAX_KEY_BITS + 1, KEY_BITS_STEP):
            m = max_outputs(n, q)
            if m > 0 and (not entries or m > entries[-1][1]):
                entries.append((n, m))
        print(f"q = {q}: {entries[0]} ... {entries[-1]}", file=sys.stderr)
        tables[q] = entries

    print(f"""// Generated by tools/local_key_bits.py; do not edit.
//
// For each number q of products of the local PRG and each key length n, the largest number of
// outputs N for which the estimated cost of recovering the key is at least 2^{SECURITY_BITS} (guess and
// determine, and the dense MQ estimate of tools/mq_key_bits.py). This is a rough estimate for
// experiments, not a security analysis; see tools/local_key_bits.py for the caveats.

#ifndef VOLE_MOLE_MQ_LOCAL_KEY_BITS_HPP
#define VOLE_MOLE_MQ_LOCAL_KEY_BITS_HPP

#include "mq/key_bits.hpp"

#include <array>

namespace vole_mole::mq::detail {{
""")
    for q, entries in tables.items():
        print(f"constexpr std::array LOCAL_KEY_BITS_TABLE_{q} = {{")
        for n, m in entries:
            print(f"    KeyBitsEntry{{{n}, {m}}},")
        print("};\n")
    print("""} // namespace vole_mole::mq::detail

#endif""")


if __name__ == "__main__":
    main()
