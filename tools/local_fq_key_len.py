#!/usr/bin/env python3
"""Generate the key length tables of the local PRG over F_q (src/voleith_fq/local_key_len.hpp).

The local PRG over F_q (see src/voleith_fq/local.hpp) stretches a key K in F_q^n into N outputs

  y_i = c_{i,1} K_{l_1} + ... + c_{i,L} K_{l_L} + K_{a} K_{b}

for public, pseudorandom, distinct indices and nonzero coefficients: Goldreich's PRG with the
predicate XOR_L-AND_2, over F_q. As tools/local_key_bits.py, for each key length n this estimates
the largest N for which recovering K costs at least 2^SECURITY_BITS against

  - guess and determine (Couteau et al., Asiacrypt 2018): guess g key elements (cost q^g); an
    output becomes linear if its product contains a guessed element, with probability
    p = 1 - (1 - g / n)^2; once N p >= n - g, solve. Cost q^g (n - g)^2, minimized over g.
  - (DENSE table only) the dense MQ estimate of tools/mq_fq_key_len.py, as a heuristic floor: we
    assume a sparse system is no harder to solve than a dense one.

Over F_q, guessing costs log2(q) = 11.7 bits per element, so guess and determine is far from
binding and the DENSE table equals the dense MQ PRG's key lengths. The GD table (guess and
determine only) is NOT a security estimate: algebraic attacks on sparse systems may well be the
binding ones (Couteau et al. find so over GF(2)). It's here to show what the proof size would be if
the sparse structure didn't help the attacker beyond guess and determine.

Usage: tools/local_fq_key_len.py > src/voleith_fq/local_key_len.hpp
"""

import sys
from math import log2

import mq_fq_key_len as dense

SECURITY_BITS = 128
Q = dense.Q
MIN_KEY_LEN = 16
MAX_KEY_LEN = 320
KEY_LEN_STEP = 2


def log2_cost_gd(n, m):
    for g in range(1, n):
        p = 1 - (1 - g / n) ** 2
        if m * p >= n - g:
            return g * log2(Q) + 2 * log2(n - g)
    return n * log2(Q)


def max_outputs_gd(n):
    if log2_cost_gd(n, n) < SECURITY_BITS:
        return 0
    lo, hi = n, 64 * n
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if log2_cost_gd(n, mid) >= SECURITY_BITS:
            lo = mid
        else:
            hi = mid
    return lo


def table(f):
    entries = []
    for n in range(MIN_KEY_LEN, MAX_KEY_LEN + 1, KEY_LEN_STEP):
        m = f(n)
        if m > 0 and (not entries or m > entries[-1][1]):
            entries.append((n, m))
    return entries


def main():
    gd = table(max_outputs_gd)
    dn = table(lambda n: min(max_outputs_gd(n), dense.max_outputs(n)))
    print(f"""// Generated by tools/local_fq_key_len.py; do not edit.
//
// Key lengths of the local PRG over F_q: for each key length n, the largest number of outputs N
// for which the estimated cost of recovering the key is at least 2^{SECURITY_BITS}. LOCAL_KEY_LEN_TABLE_DENSE
// takes the dense MQ estimate as a floor; LOCAL_KEY_LEN_TABLE_GD only accounts for guess and
// determine and is NOT a security estimate. See tools/local_fq_key_len.py.

#ifndef VOLE_MOLE_VOLEITH_FQ_LOCAL_KEY_LEN_HPP
#define VOLE_MOLE_VOLEITH_FQ_LOCAL_KEY_LEN_HPP

#include "voleith_fq/mq_key_len.hpp"

#include <array>

namespace vole_mole::voleith_fq::detail {{
""")
    for name, entries in (("DENSE", dn), ("GD", gd)):
        print(f"constexpr std::array LOCAL_KEY_LEN_TABLE_{name} = {{")
        for n, m in entries:
            print(f"    MqKeyLenEntry{{{n}, {m}}},")
        print("};\n")
    print("""} // namespace vole_mole::voleith_fq::detail

#endif""")


if __name__ == "__main__":
    main()
