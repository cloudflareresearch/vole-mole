#!/usr/bin/env python3
"""Reference implementation of the MQ PRG (src/mq/prg.hpp), used to generate tests/mq/kat.txt.

AES4 (AES-128 reduced to 4 rounds) is implemented here in pure Python. The same code with 10
rounds is checked against the `cryptography` package's AES-128, which is required.

Usage: tools/mq_ref.py > tests/mq/kat.txt
"""

import hashlib

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def _xtime(a):
    return ((a << 1) ^ 0x1B) & 0xFF if a & 0x80 else a << 1


def _gf_mul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a, b = _xtime(a), b >> 1
    return r


def _sbox():
    box = []
    for x in range(256):
        inv = next((y for y in range(1, 256) if _gf_mul(x, y) == 1), 0)
        s = inv
        for shift in range(1, 5):
            s ^= ((inv << shift) | (inv >> (8 - shift))) & 0xFF
        box.append(s ^ 0x63)
    return box


SBOX = _sbox()


def aes128_round_keys(key, rounds):
    """The first rounds + 1 round keys of the AES-128 key schedule."""
    words = [list(key[4 * i : 4 * i + 4]) for i in range(4)]
    rcon = 1
    while len(words) < 4 * (rounds + 1):
        t = list(words[-1])
        if len(words) % 4 == 0:
            t = [SBOX[b] for b in t[1:] + t[:1]]
            t[0] ^= rcon
            rcon = _xtime(rcon)
        words.append([a ^ b for a, b in zip(words[-4], t)])
    return [bytes(sum(words[4 * r : 4 * r + 4], [])) for r in range(rounds + 1)]


def aes_encrypt(round_keys, block):
    """AES-128 with len(round_keys) - 1 rounds; the last round omits MixColumns."""
    rounds = len(round_keys) - 1
    s = [a ^ b for a, b in zip(block, round_keys[0])]  # column-major state
    for r in range(1, rounds + 1):
        s = [SBOX[b] for b in s]
        s = [s[(i + 4 * (i % 4)) % 16] for i in range(16)]  # ShiftRows
        if r < rounds:
            out = []
            for c in range(4):
                a = s[4 * c : 4 * c + 4]
                out += [
                    _xtime(a[0]) ^ _xtime(a[1]) ^ a[1] ^ a[2] ^ a[3],
                    a[0] ^ _xtime(a[1]) ^ _xtime(a[2]) ^ a[2] ^ a[3],
                    a[0] ^ a[1] ^ _xtime(a[2]) ^ _xtime(a[3]) ^ a[3],
                    _xtime(a[0]) ^ a[0] ^ a[1] ^ a[2] ^ _xtime(a[3]),
                ]
            s = out
        s = [a ^ b for a, b in zip(s, round_keys[r])]
    return bytes(s)


def _self_test():
    key, block = bytes(range(16)), bytes(range(16, 32))
    enc = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
    expected = enc.update(block) + enc.finalize()
    assert aes_encrypt(aes128_round_keys(key, 10), block) == expected, "AES-128 mismatch"


AES4_ROUNDS = 4


def aes_key(dst, n, num_outputs):
    data = dst + n.to_bytes(4, "little") + num_outputs.to_bytes(4, "little")
    return hashlib.shake_128(data).digest(16)


def packed_bytes(n):
    """Length of a packed upper-triangular matrix: row j holds bytes j // 8, ..., n // 8 - 1."""
    return sum(n // 8 - j // 8 for j in range(n))


def matrix(key, n, i):
    """The packed coefficient matrix of output i, padded to whole 16-byte blocks."""
    blocks = (packed_bytes(n) + 15) // 16
    rk = aes128_round_keys(key, AES4_ROUNDS)
    return b"".join(
        aes_encrypt(rk, (i * blocks + t).to_bytes(8, "little") + bytes(8)) for t in range(blocks)
    )


def full_rows(m, n):
    """Unpack a packed matrix into n full rows of n // 8 bytes (with garbage below the diagonal)."""
    rows, off = [], 0
    for j in range(n):
        length = n // 8 - j // 8
        rows.append(bytes(j // 8) + m[off : off + length])
        off += length
    return rows


def bit(data, k):
    return (data[k // 8] >> (k % 8)) & 1


def evaluate(dst, n, num_outputs, k):
    key = aes_key(dst, n, num_outputs)
    out = bytearray(num_outputs // 8)
    for i in range(num_outputs):
        rows = full_rows(matrix(key, n, i), n)
        acc = 0
        for j in range(n):
            if not bit(k, j):
                continue
            for kk in range(j, n):
                acc ^= bit(rows[j], kk) & bit(k, kk)
        out[i // 8] |= acc << (i % 8)
    return bytes(out)


def main():
    _self_test()
    print("# MQ PRG known answers, generated by tools/mq_ref.py.")
    print("# Each record: dst, key bits n, outputs N, key K, the first 32 bytes of the packed")
    print("# matrix M_1, G(K).")
    cases = [
        (b"mqtest0", 144, 128, bytes(range(18))),
        (b"mqtest1", 160, 64, bytes([0xff] * 20)),
        (b"mqtest1", 160, 64, bytes([0x5a, 0x01] * 10)),
        (b"mqtest2", 136, 64, bytes(range(0x80, 0x80 + 17))),  # not a multiple of 16
    ]
    for dst, n, num_outputs, k in cases:
        assert len(k) == n // 8
        print()
        print("dst", dst.hex())
        print("n", n)
        print("N", num_outputs)
        print("key", k.hex())
        print("matrix1", matrix(aes_key(dst, n, num_outputs), n, 1)[:32].hex())
        print("output", evaluate(dst, n, num_outputs, k).hex())


if __name__ == "__main__":
    main()
