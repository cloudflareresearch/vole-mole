#!/usr/bin/env python3
"""Generate the key length table of the local PRG over F_p (src/voleith_p256/prg_key_len.hpp).

The PRG (see src/voleith_p256/prg.hpp) stretches a key K in F^n into m outputs over a prime field
F of about 256 bits (F_p or F_n of P-256), each of the form

  y_i = sum_{t < L} c_{i,t} K_{l_{i,t}} + sum_{s < Q} c'_{i,s} K_{a_{i,s}} K_{b_{i,s}}

with public, pseudorandom, distinct indices and nonzero coefficients. For each key length n (a
multiple of KEY_STEP), this script estimates the largest m for which recovering K from G(K) still
costs at least 2^SECURITY_BITS.

Over a field this large, the attacks that dominate over GF(2) don't apply: guessing a single key
element costs 2^256, so guess-and-determine and hybrid algebraic attacks are useless. What remains
are algebraic attacks, for which we use the same heuristic floor as tools/local_key_bits.py: the
system is assumed to be no easier than a dense, semi-regular system of m quadratic equations in n
unknowns. Its degree of regularity D_reg is the index of the first non-positive coefficient of the
Hilbert series (1 - z^2)^m / (1 - z)^n (Bardet, Faugere, Salvy), and solving it costs (number of
monomials of degree <= D_reg)^OMEGA = C(n + D_reg, D_reg)^OMEGA, with OMEGA = 2 (sparse linear
algebra, which is conservative for the defender).

Each output's L + 2 Q indices are distinct, so the locality L + 2 Q is a large fraction of n; at
the stretch m / n < 4 we use, no small set of outputs depends on fewer key elements than it has
outputs (as a subsystem attack would need), and no linear combination of the quadratic parts of
the outputs vanishes (their supports are almost disjoint), which would give linear equations.

This is a first, rough estimate for performance experiments, NOT a security analysis: it ignores
distinguishers that don't recover the key, and it should be checked against the literature on
algebraic attacks on sparse and local systems over large fields before relying on it.

Usage: tools/fp_prg_key_len.py | clang-format --assume-filename=src/voleith_p256/prg_key_len.hpp \\
  > src/voleith_p256/prg_key_len.hpp
"""

import sys
from math import comb, log2

SECURITY_BITS = 128
OMEGA = 2
MIN_KEY = 32
MAX_KEY = 320
KEY_STEP = 4


def degree_of_regularity(n, m):
    """Index of the first non-positive coefficient of (1 - z^2)^m / (1 - z)^n."""
    d = 0
    while True:
        coeff = sum((-1) ** k * comb(m, k) * comb(n - 1 + d - 2 * k, d - 2 * k)
                    for k in range(d // 2 + 1))
        if coeff <= 0:
            return d
        d += 1


def log2_cost(n, m):
    d = degree_of_regularity(n, m)
    return OMEGA * log2(comb(n + d, d))


def max_outputs(n):
    """The largest m >= n with log2_cost(n, m) >= SECURITY_BITS, or 0 if there is none."""
    if log2_cost(n, n) < SECURITY_BITS:
        return 0
    lo, hi = n, comb(n + 2, 2)  # beyond hi, linearization breaks the system
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if log2_cost(n, mid) >= SECURITY_BITS:
            lo = mid
        else:
            hi = mid
    return lo


def main():
    entries = []
    for n in range(MIN_KEY, MAX_KEY + 1, KEY_STEP):
        m = max_outputs(n)
        if m > n and (not entries or m > entries[-1][1]):
            entries.append((n, m))
    out = sys.stdout
    out.write("// Generated by tools/fp_prg_key_len.py; do not edit.\n")
    out.write("//\n")
    out.write("// The key lengths of the local PRG over F_p (prg.hpp): for each key length n, the\n")
    out.write(f"// largest number of outputs with an estimated cost of at least 2^{SECURITY_BITS}\n")
    out.write("// to recover the key (see the script for the estimate, which is NOT a security\n")
    out.write("// analysis).\n\n")
    out.write("#ifndef VOLE_MOLE_VOLEITH_P256_PRG_KEY_LEN_HPP\n")
    out.write("#define VOLE_MOLE_VOLEITH_P256_PRG_KEY_LEN_HPP\n\n")
    out.write("#include <array>\n#include <cstddef>\n\n")
    out.write("namespace vole_mole::voleith_p256::detail {\n\n")
    out.write("struct PrgKeyLen {\n    size_t key, max_outputs;\n};\n\n")
    out.write(f"constexpr std::array<PrgKeyLen, {len(entries)}> PRG_KEY_LENS = {{\n")
    for n, m in entries:
        out.write(f"    PrgKeyLen{{{n}, {m}}},\n")
    out.write("};\n\n")
    out.write("} // namespace vole_mole::voleith_p256::detail\n\n#endif\n")


if __name__ == "__main__":
    main()
