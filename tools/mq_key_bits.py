#!/usr/bin/env python3
"""Generate the key length table of the MQ PRG (src/mq/key_bits.hpp).

The MQ PRG stretches a key K of n bits into N output bits, each a random quadratic form in K over
GF(2). For each key length n (a multiple of 16), this script estimates the largest number of
outputs N for which distinguishing G(K) from random still costs at least 2^SECURITY_BITS, i.e.,
for which the system G(K) = y in n unknowns and N equations is hard to solve.

The estimate is deliberately simple and should be checked against the CryptographicEstimators
library (MQEstimator) before relying on it:

  - The system is assumed semi-regular, so its degree of regularity D_reg is the index of the
    first non-positive coefficient of the Hilbert series (1 + z)^n / (1 + z^2)^N (Bardet, Faugere,
    Salvy).
  - Solving costs (number of monomials of degree <= D_reg)^OMEGA, as for XL with sparse linear
    algebra (OMEGA = 2), minimized over the hybrid approach of guessing g variables first, which
    multiplies the cost by 2^g.

Usage: tools/mq_key_bits.py > src/mq/key_bits.hpp
"""

import sys
from math import comb, log2

SECURITY_BITS = 128
OMEGA = 2
MIN_KEY_BITS = 128
MAX_KEY_BITS = 1024
KEY_BITS_STEP = 16
MAX_GUESSED = 64


def degree_of_regularity(n, m):
    """Index of the first non-positive coefficient of (1 + z)^n / (1 + z^2)^m, or None."""
    for d in range(n + 1):
        coeff = sum((-1) ** k * comb(m + k - 1, k) * comb(n, d - 2 * k) for k in range(d // 2 + 1))
        if coeff <= 0:
            return d
    return None


def log2_cost(n, m):
    """log2 of the estimated cost of solving m random quadratic equations in n variables."""
    best = None
    for g in range(min(MAX_GUESSED, n - 1) + 1):
        d = degree_of_regularity(n - g, m)
        if d is None:
            continue
        monomials = sum(comb(n - g, i) for i in range(d + 1))
        cost = g + OMEGA * log2(monomials)
        best = cost if best is None else min(best, cost)
    return best


def max_outputs(n):
    """The largest m for which log2_cost(n, m) >= SECURITY_BITS, or 0 if there is none."""
    if log2_cost(n, n) < SECURITY_BITS:
        return 0
    lo, hi = n, n + comb(n, 2)  # beyond hi, linearization breaks the system
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if log2_cost(n, mid) >= SECURITY_BITS:
            lo = mid
        else:
            hi = mid
    return lo


def main():
    entries = []
    for n in range(MIN_KEY_BITS, MAX_KEY_BITS + 1, KEY_BITS_STEP):
        m = max_outputs(n)
        print(f"n = {n}: N <= {m}", file=sys.stderr)
        if m > 0:
            entries.append((n, m))

    print(f"""// Generated by tools/mq_key_bits.py; do not edit.
//
// For each key length n of the MQ PRG, the largest number of outputs N for which the estimated
// cost of solving N random quadratic equations in n variables over GF(2) is at least
// 2^{SECURITY_BITS} (semi-regular D_reg, XL with omega = {OMEGA}, hybrid guessing). See
// tools/mq_key_bits.py for the caveats.

#ifndef VOLE_MOLE_MQ_KEY_BITS_HPP
#define VOLE_MOLE_MQ_KEY_BITS_HPP

#include <array>
#include <cstddef>

namespace vole_mole::mq::detail {{

struct KeyBitsEntry {{
    size_t key_bits;
    size_t max_outputs;
}};

constexpr size_t KEY_BITS_SECURITY = {SECURITY_BITS};

constexpr std::array KEY_BITS_TABLE = {{""")
    for n, m in entries:
        print(f"    KeyBitsEntry{{{n}, {m}}},")
    print("""};

} // namespace vole_mole::mq::detail

#endif""")


if __name__ == "__main__":
    main()
