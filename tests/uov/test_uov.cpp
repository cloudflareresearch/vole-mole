namespace {

using vole_mole::uov::detail::for_each_monomial;

const moussaka::Context CTX_ISS = filled<moussaka::CTX_BYTES>(0x10);
const moussaka::Context CTX_RED = filled<moussaka::CTX_BYTES>(0x20);
const moussaka::Nullifier NF = filled<moussaka::NF_BYTES>(0x30);
const moussaka::detail::Opening R = filled<moussaka::detail::R_BYTES>(0x40);

const uov::Target T = filled<uov::M>(0x70);

// Multiplication in GF(256) = GF(2)[x] / (x^8 + x^4 + x^3 + x + 1), as in UOV.
uint8_t gf256_mul(uint8_t a, uint8_t b) {
    uint8_t out = 0;
    for (size_t i = 0; i < 8; ++i) {
        if ((b >> i) & 1) {
            out ^= a;
        }
        a = static_cast<uint8_t>((a << 1) ^ ((a >> 7) * 0x1b));
    }
    return out;
}

} // namespace

TEST(Uov, DerivePreimageOfCommitment) {
    const auto& [pk, sk] = uov_key_pair();
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    const uov::Preimage w = sk.derive_preimage(t);
    EXPECT_EQ(to_hex(pk.eval(w)), to_hex(t));
}

TEST(Uov, DerivePreimageIsDeterministic) {
    const auto& [pk, sk] = uov_key_pair();
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    EXPECT_EQ(to_hex(sk.derive_preimage(t)), to_hex(sk.derive_preimage(t)));

    // A different target has a different preimage.
    moussaka::detail::Opening r2 = R;
    r2[0] ^= 1;
    const moussaka::detail::Commitment t2 = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, r2);
    const uov::Preimage w2 = sk.derive_preimage(t2);
    EXPECT_NE(to_hex(w2), to_hex(sk.derive_preimage(t)));
    EXPECT_EQ(to_hex(pk.eval(w2)), to_hex(t2));
}

TEST(Uov, SecretKeyExpansionIsDeterministic) {
    const auto& [pk, sk] = uov_key_pair();
    const uov::SecretKey sk2(UOV_SK_BYTES);
    EXPECT_EQ(to_hex(sk2.public_key_bytes()), to_hex(sk.public_key_bytes()));
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    EXPECT_EQ(to_hex(sk2.derive_preimage(t)), to_hex(sk.derive_preimage(t)));
}

// The digest identifies the public key.
TEST(Uov, PublicKeyDigest) {
    using uov::detail::PublicKeyAccess;
    const auto& [pk, sk] = uov_key_pair();
    EXPECT_EQ(to_hex(PublicKeyAccess::digest(uov::PublicKey(sk.public_key_bytes()))),
              to_hex(PublicKeyAccess::digest(pk)));

    const uov::SecretKey other(filled<uov::SECRET_KEY_BYTES>(0x61));
    EXPECT_NE(to_hex(PublicKeyAccess::digest(uov::PublicKey(other.public_key_bytes()))),
              to_hex(PublicKeyAccess::digest(pk)));
}

// The secret key's expanded public key is the expansion of its compressed public key, and it
// survives moving the secret key.
TEST(Uov, SecretKeyHasExpandedPublicKey) {
    using uov::detail::PublicKeyAccess;
    const auto& [pk, sk] = uov_key_pair();
    const uov::PublicKey& expanded = sk.expanded_public_key();
    EXPECT_EQ(to_hex(PublicKeyAccess::digest(expanded)), to_hex(PublicKeyAccess::digest(pk)));
    EXPECT_TRUE(
        std::ranges::equal(PublicKeyAccess::expanded(expanded), PublicKeyAccess::expanded(pk)));

    uov::SecretKey sk2(UOV_SK_BYTES);
    const uov::PublicKey* before = &sk2.expanded_public_key();
    const uov::SecretKey sk3 = std::move(sk2);
    EXPECT_EQ(&sk3.expanded_public_key(), before);
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    EXPECT_EQ(to_hex(sk3.expanded_public_key().eval(sk3.derive_preimage(t))), to_hex(t));
}

TEST(Uov, GenerateSecretKeyBytes) {
    const uov::SecretKeyBytes a = uov::generate_secret_key_bytes();
    const uov::SecretKeyBytes b = uov::generate_secret_key_bytes();
    EXPECT_NE(to_hex(a), to_hex(b));

    // The generated bytes expand to a working key pair.
    const uov::SecretKey sk(a);
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    EXPECT_EQ(to_hex(sk.expanded_public_key().eval(sk.derive_preimage(t))), to_hex(t));
}

TEST(Uov, KeysAreMovable) {
    uov::SecretKey sk(UOV_SK_BYTES);
    const uov::PublicKeyBytes pk_bytes = sk.public_key_bytes();
    uov::SecretKey sk2 = std::move(sk);
    uov::PublicKey pk(pk_bytes);
    uov::PublicKey pk2 = std::move(pk);
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    EXPECT_EQ(to_hex(pk2.eval(sk2.derive_preimage(t))), to_hex(t));
}

TEST(Uov, RejectWrongKey) {
    const auto& [pk, sk] = uov_key_pair();
    const UovKeyPair other(uov::SecretKey{filled<uov::SECRET_KEY_BYTES>(0x61)});
    EXPECT_NE(to_hex(other.sk.public_key_bytes()), to_hex(sk.public_key_bytes()));
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    EXPECT_NE(to_hex(other.pk.eval(sk.derive_preimage(t))), to_hex(t));
}

TEST(Uov, RejectTamperedPublicKey) {
    const auto& [pk, sk] = uov_key_pair();
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    const uov::Preimage w = sk.derive_preimage(t);

    // Both the seed (first 16 bytes) and P3 (the rest) of the compressed key matter.
    for (const size_t i : {size_t{0}, size_t{15}, size_t{16}, uov::PUBLIC_KEY_BYTES - 1}) {
        uov::PublicKeyBytes bad = sk.public_key_bytes();
        bad[i] ^= 1;
        EXPECT_NE(to_hex(uov::PublicKey(bad).eval(w)), to_hex(t)) << "flipped a bit of byte " << i;
    }
}

TEST(Uov, RejectTamperedPreimage) {
    const auto& [pk, sk] = uov_key_pair();
    const moussaka::detail::Commitment t = moussaka::detail::commit(NF, CTX_ISS, CTX_RED, R);
    const uov::Preimage w = sk.derive_preimage(t);
    for (size_t i = 0; i < w.size(); i += 7) {
        uov::Preimage bad = w;
        bad[i] ^= 1;
        EXPECT_NE(to_hex(pk.eval(bad)), to_hex(t)) << "flipped a bit of byte " << i;
    }
}

// Test that the UOV public map circuit properly embeds GF(256) in GF(2^128).
TEST(UovCircuit, EmbeddingIsHomomorphism) {
    using QS = faest::quicksilver_state<faest::secpar::s128, true, 2>;
    const auto embed = uov::detail::embed<QS>;
    for (unsigned a = 0; a < 256; ++a) {
        for (unsigned b = 0; b < 256; ++b) {
            const auto x = static_cast<uint8_t>(a);
            const auto y = static_cast<uint8_t>(b);
            ASSERT_TRUE(embed(x) + embed(y) == embed(x ^ y)) << a << " + " << b;
            ASSERT_TRUE((embed(x) * embed(y)).reduce_to<128>() == embed(gf256_mul(x, y)))
                << a << " * " << b;
        }
    }
}

TEST(UovCircuit, ForEachMonomialEvaluatesPublicMap) {
    const auto& [pk, sk] = uov_key_pair();
    const uov::Preimage s = sk.derive_preimage(T);

    uov::Target got{};
    size_t num_monomials = 0;
    for_each_monomial(uov::detail::PublicKeyAccess::expanded(pk),
                      [&](size_t i, size_t j, std::span<const uint8_t, uov::M> coeffs) {
                          ASSERT_LE(i, j);
                          const uint8_t monomial = gf256_mul(s[i], s[j]);
                          for (size_t k = 0; k < uov::M; ++k) {
                              got[k] ^= gf256_mul(coeffs[k], monomial);
                          }
                          ++num_monomials;
                      });
    EXPECT_EQ(num_monomials, uov::N * (uov::N + 1) / 2);
    EXPECT_EQ(to_hex(got), to_hex(T));
    EXPECT_EQ(to_hex(got), to_hex(pk.eval(s)));
}

namespace {

using QS = faest::quicksilver_state<faest::secpar::s128, false, 2>;
using Combination = uov::detail::Combination<QS>;
using poly = Combination::poly;

// sum_k l[k] * t[k] in the clear.
poly combine_plain(const Combination& l, const uov::Target& t) {
    poly out = poly::set_zero();
    for (size_t k = 0; k < uov::M; ++k) {
        out = out + (l.coeff(k) * uov::detail::embed<QS>(t[k])).reduce_to<128>();
    }
    return out;
}

// Evaluate the combined public map circuit at s with the QuickSilver prover's types, which track
// the value of each committed element (with arbitrary VOLE tags), and check that the result is the
// combination of `want`.
void expect_circuit_eval(const uov::PublicKey& pk, const uov::Preimage& s, const uov::Target& want,
                         const Combination& l) {
    std::vector<faest::block_secpar<faest::secpar::s128>> macs(8 * uov::N);
    std::array<uint8_t, faest::QS_CONSTANTS<faest::secpar::s128, 2>::CHALLENGE_BYTES> challenge{};
    const QS qs(s.data(), macs.data(), 1, challenge.data());

    std::array<uov::detail::qs_val<QS, 1>, uov::N> s_committed;
    for (size_t i = 0; i < uov::N; ++i) {
        s_committed[i] = qs.load_witness_8_bits_and_combine(8 * i);
    }
    const auto p = uov::detail::qs_eval_combined_public_map<QS>(pk, s_committed, l);
    EXPECT_TRUE(p.value() == combine_plain(l, want)) << "at s = " << to_hex(s);
}

// A combination derived from an arbitrary challenge.
const Combination& combination() {
    static const Combination l(filled<Combination::CHALLENGE_BYTES>(0x70),
                               std::array<uint8_t, 3>{'d', 's', 't'});
    return l;
}

} // namespace

TEST(UovCircuit, CircuitEvalCombinedPublicMapMatchesPlaintext) {
    const auto& [pk, sk] = uov_key_pair();
    expect_circuit_eval(pk, sk.derive_preimage(T), T, combination());

    const UovKeyPair other(uov::SecretKey{filled<uov::SECRET_KEY_BYTES>(0x61)});
    std::mt19937 rng(0); // fixed seed, so that failures are reproducible
    for (const uov::PublicKey* public_key : {&pk, &other.pk}) {
        uov::Preimage ones;
        ones.fill(0xff);
        std::vector<uov::Preimage> points = {uov::Preimage{}, ones};
        for (int n = 0; n < 8; ++n) {
            uov::Preimage s;
            for (uint8_t& b : s) {
                b = static_cast<uint8_t>(rng());
            }
            points.push_back(s);
        }
        for (const uov::Preimage& s : points) {
            expect_circuit_eval(*public_key, s, public_key->eval(s), combination());
        }
    }
}

// Each coefficient of the combination is used: with the unit vector e_k as the combination, the
// circuit evaluates the k-th component of P(s).
TEST(UovCircuit, CircuitEvalCombinedPublicMapUnitVectors) {
    const auto& [pk, sk] = uov_key_pair();
    const uov::Preimage s = sk.derive_preimage(T);
    for (size_t k = 0; k < uov::M; ++k) {
        std::array<poly, uov::M> e;
        e.fill(poly::set_zero());
        e[k] = uov::detail::embed<QS>(1);
        expect_circuit_eval(pk, s, T, Combination(e));
    }
}

// The combination is derived deterministically from the challenge and DST, and depends on both.
TEST(UovCircuit, CombinationDependsOnChallengeAndDst) {
    const auto chal = filled<Combination::CHALLENGE_BYTES>(0x70);
    const std::array<uint8_t, 3> dst = {'d', 's', 't'};
    const std::array<uint8_t, 3> other_dst = {'d', 's', 'u'};
    auto other_chal = chal;
    other_chal[0] ^= 1;
    const Combination a(chal, dst), b(chal, dst), c(other_chal, dst), d(chal, other_dst);
    for (size_t k = 0; k < uov::M; ++k) {
        EXPECT_TRUE(a.coeff(k) == b.coeff(k));
        EXPECT_FALSE(a.coeff(k) == c.coeff(k));
        EXPECT_FALSE(a.coeff(k) == d.coeff(k));
    }
}

// A target that differs from P(s) in a single component is detected by the combination.
TEST(UovCircuit, CombinationDetectsWrongComponent) {
    for (size_t k = 0; k < uov::M; ++k) {
        uov::Target wrong = T;
        wrong[k] ^= 1;
        EXPECT_FALSE(combine_plain(combination(), wrong) == combine_plain(combination(), T))
            << "component " << k;
    }
}
