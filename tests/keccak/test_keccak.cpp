// Path of a test data file, relative to tests/ in the source tree. (VOLE_MOLE_TEST_DATA_DIR is
// set by tests/meson.build, so test executables can be run from any directory.)
std::string data_path(std::string_view relative) {
    return std::string(VOLE_MOLE_TEST_DATA_DIR) + "/" + std::string(relative);
}

// Read a known-answer file: one record per line, fields separated by whitespace. Blank lines and
// lines starting with '#' are skipped. Returns nothing if the file can't be opened.
std::optional<std::vector<std::vector<std::string>>> read_records(const std::string& path) {
    std::ifstream in(path);
    if (!in) {
        return std::nullopt;
    }
    std::vector<std::vector<std::string>> records;
    for (std::string line; std::getline(in, line);) {
        if (line.empty() || line[0] == '#') {
            continue;
        }
        std::istringstream fields(line);
        std::vector<std::string> record;
        for (std::string field; fields >> field;) {
            record.push_back(field);
        }
        if (!record.empty()) {
            records.push_back(std::move(record));
        }
    }
    return records;
}

// Parse a hex-encoded Keccak state, or return nothing if it is malformed.
std::optional<Kp800State> parse_state(const std::string& hex) {
    const auto bytes = hex_decode(hex);
    if (!bytes || bytes->size() != KP800_STATE_BYTES) {
        return std::nullopt;
    }
    Kp800State state;
    std::ranges::copy(*bytes, state.begin());
    return state;
}

