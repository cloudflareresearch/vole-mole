// Known answers for the full permutation, generated by keccak/keccak_ref.py.
TEST(Keccak, KnownAnswers) {
    const auto records = read_records(data_path("keccak/kat.txt"));
    ASSERT_TRUE(records.has_value()) << "can't open keccak/kat.txt";
    ASSERT_FALSE(records->empty());
    ASSERT_EQ(records->size() % 2, 0u);
    for (size_t i = 0; i < records->size(); i += 2) {
        SCOPED_TRACE("known answer " + std::to_string(i / 2));
        const auto& in = (*records)[i];
        const auto& out = (*records)[i + 1];
        ASSERT_TRUE(in.size() == 2 && in[0] == "input" && out.size() == 2 && out[0] == "output");
        const auto input = parse_state(in[1]);
        ASSERT_TRUE(input.has_value()) << "malformed input: " << in[1];
        EXPECT_EQ(to_hex(keccak_p800(*input)), out[1]);
    }
}

TEST(Keccak, RoundsCompose) {
    Kp800State a;
    for (size_t i = 0; i < a.size(); ++i) {
        a[i] = static_cast<uint8_t>(7 * i + 3);
    }
    Kp800State b = a;
    keccak_p800_rounds(b, 0, 3);
    keccak_p800_rounds(b, 3, 5);
    keccak_p800_rounds(b, 8, 4);
    EXPECT_EQ(to_hex(b), to_hex(keccak_p800(a)));
}

struct Bit {
    bool v;
    Bit operator+(Bit o) const { return {v != o.v}; }
};

// The bit-level circuit used for the VOLE-in-the-Head proof computes the same function as the
// plaintext, lane-based implementation.
TEST(Keccak, CircuitMatchesLanes) {
    Kp800State input;
    for (size_t i = 0; i < input.size(); ++i) {
        input[i] = static_cast<uint8_t>(i * i + 1);
    }

    std::vector<Bit> bits(KP800_STATE_BITS);
    for (size_t i = 0; i < bits.size(); ++i) {
        bits[i] = {((input[i / 8] >> (i % 8)) & 1) != 0};
    }

    const auto chi = [](Bit a, Bit b, Bit c) { return Bit{a.v != (!b.v && c.v)}; };
    const auto add_one = [](Bit x) { return Bit{!x.v}; };
    for (size_t r = 0; r < KP800_ROUNDS; ++r) {
        bits = detail::keccak_round(bits, r, chi, add_one);
    }

    Kp800State output{};
    for (size_t i = 0; i < bits.size(); ++i) {
        output[i / 8] |= static_cast<uint8_t>(bits[i].v << (i % 8));
    }
    EXPECT_EQ(to_hex(output), to_hex(keccak_p800(input)));
}

// The bit-level inverse rounds undo the plaintext rounds, one round at a time and for the full
// permutation.
TEST(Keccak, InverseCircuitInvertsLanes) {
    const auto to_bits = [](const Kp800State& s) {
        std::vector<Bit> bits(KP800_STATE_BITS);
        for (size_t i = 0; i < bits.size(); ++i) {
            bits[i] = {((s[i / 8] >> (i % 8)) & 1) != 0};
        }
        return bits;
    };
    const auto chi_inv = [](Bit a, Bit b, Bit c, Bit d, Bit e) {
        return Bit{a.v != (!b.v && (c.v != (!d.v && e.v)))};
    };
    const auto add_one = [](Bit x) { return Bit{!x.v}; };

    Kp800State input;
    for (size_t i = 0; i < input.size(); ++i) {
        input[i] = static_cast<uint8_t>(5 * i * i + 11 * i + 2);
    }

    // Single rounds.
    for (size_t r = 0; r < KP800_ROUNDS; ++r) {
        SCOPED_TRACE("round " + std::to_string(r));
        Kp800State output = input;
        keccak_p800_rounds(output, r, 1);
        const auto bits = detail::keccak_round_inverse(to_bits(output), r, chi_inv, add_one);
        EXPECT_EQ(bits.size(), KP800_STATE_BITS);
        bool equal = true;
        for (size_t i = 0; i < bits.size(); ++i) {
            equal &= bits[i].v == (((input[i / 8] >> (i % 8)) & 1) != 0);
        }
        EXPECT_TRUE(equal);
    }

    // Full permutation.
    auto bits = to_bits(keccak_p800(input));
    for (size_t r = KP800_ROUNDS; r-- > 0;) {
        bits = detail::keccak_round_inverse(bits, r, chi_inv, add_one);
    }
    Kp800State recovered{};
    for (size_t i = 0; i < bits.size(); ++i) {
        recovered[i / 8] |= static_cast<uint8_t>(bits[i].v << (i % 8));
    }
    EXPECT_EQ(to_hex(recovered), to_hex(input));
}

// Soundness of the arithmetization in keccak/segmented.hpp (see lean/docs/extraction/L7-keccak.md). The
// tests below evaluate the QuickSilver circuit itself, instantiated with the plaintext stand-in
// PlainQS, so they test the very chi and chi^-1 lambdas that generate the constraints.
namespace {

using vole_mole::test::PlainQS;
template <size_t deg> using PlainBit = faest::quicksilver_gf2<PlainQS, deg>;
template <size_t deg = 1> using PlainState = std::vector<PlainBit<deg>>;

template <size_t deg = 1> PlainState<deg> to_plain(const Kp800State& s) {
    PlainState<deg> bits;
    bits.reserve(KP800_STATE_BITS);
    for (size_t i = 0; i < KP800_STATE_BITS; ++i) {
        bits.emplace_back(((s[i / 8] >> (i % 8)) & 1) != 0);
    }
    return bits;
}

template <size_t deg> Kp800State from_plain(const PlainState<deg>& bits) {
    Kp800State s{};
    for (size_t i = 0; i < bits.size(); ++i) {
        s[i / 8] |= static_cast<uint8_t>(bits[i].v << (i % 8));
    }
    return s;
}

Kp800State unit_state(size_t i) {
    Kp800State s{};
    s[i / 8] = static_cast<uint8_t>(1u << (i % 8));
    return s;
}

// A state in which row (y, z) (the five bits (x, y, z) for x < 5) holds the value
// (v + 7 y + 3 z) % 32, with bit x of the value at x. For v = 0, ..., 31, every row takes every
// value exactly once.
Kp800State row_state(size_t v) {
    Kp800State s{};
    for (size_t y = 0; y < 5; ++y) {
        for (size_t z = 0; z < detail::KECCAK_W; ++z) {
            const size_t row = (v + 7 * y + 3 * z) % 32;
            for (size_t x = 0; x < 5; ++x) {
                const size_t i = detail::keccak_bit_index(x, y, z);
                s[i / 8] |= static_cast<uint8_t>(((row >> x) & 1) << (i % 8));
            }
        }
    }
    return s;
}

Kp800State random_state(std::mt19937_64& rng) {
    Kp800State s;
    for (uint8_t& b : s) {
        b = static_cast<uint8_t>(rng());
    }
    return s;
}

} // namespace

// The linear layer L = pi o rho o theta and its inverse are GF(2)-linear (`T` only needs `+`, so
// each output bit is the XOR of a fixed set of input bits, without constants). Hence checking that
// L^-1 L and L L^-1 fix every unit vector proves that they're the identity, i.e., that
// keccak_theta_rho_pi_inverse is exactly the inverse of keccak_theta_rho_pi.
TEST(Keccak, LinearLayerInverseOnBasis) {
    for (size_t i = 0; i < KP800_STATE_BITS; ++i) {
        const auto e = to_plain(unit_state(i));
        EXPECT_EQ(from_plain(detail::keccak_theta_rho_pi_inverse(detail::keccak_theta_rho_pi(e))),
                  unit_state(i))
            << "L^-1 L e_" << i;
        EXPECT_EQ(from_plain(detail::keccak_theta_rho_pi(detail::keccak_theta_rho_pi_inverse(e))),
                  unit_state(i))
            << "L L^-1 e_" << i;
    }
}

// chi (as generated by qs_keccak_round) and chi^-1 (as generated by qs_keccak_iota_chi_inverse)
// are inverse permutations: chi acts on each 5-bit row independently, and row_state covers all 32
// values of every row. Composing with L^-1 isolates iota o chi from qs_keccak_round, whose linear
// layer is L.
TEST(Keccak, ChiInverseExhaustive) {
    using namespace keccak::detail;
    for (size_t r = 0; r < KP800_ROUNDS; ++r) {
        for (size_t v = 0; v < 32; ++v) {
            SCOPED_TRACE("round " + std::to_string(r) + ", rows " + std::to_string(v));
            const Kp800State s = row_state(v);

            // chi^-1 (chi (s)) = s
            const auto chi_s =
                qs_keccak_round<PlainQS, 1>(detail::keccak_theta_rho_pi_inverse(to_plain(s)), r);
            const auto back = qs_keccak_iota_chi_inverse<PlainQS, 2>(chi_s, r);
            EXPECT_EQ(from_plain(back), s);

            // chi (chi^-1 (s)) = s
            const auto inv_s = qs_keccak_iota_chi_inverse<PlainQS, 1>(to_plain(s), r);
            const auto fwd =
                qs_keccak_round<PlainQS, 3>(detail::keccak_theta_rho_pi_inverse(inv_s), r);
            EXPECT_EQ(from_plain(fwd), s);

            // ... and chi is a ^ (~b & c) on each row, as in keccak.cpp.
            Kp800State want = s;
            for (size_t y = 0; y < 5; ++y) {
                for (size_t z = 0; z < detail::KECCAK_W; ++z) {
                    for (size_t x = 0; x < 5; ++x) {
                        const auto bit = [&s](size_t i) { return (s[i / 8] >> (i % 8)) & 1; };
                        const size_t i = detail::keccak_bit_index(x, y, z);
                        const unsigned out =
                            bit(i) ^ ((bit(detail::keccak_bit_index((x + 1) % 5, y, z)) ^ 1) &
                                      bit(detail::keccak_bit_index((x + 2) % 5, y, z)));
                        want[i / 8] = static_cast<uint8_t>((want[i / 8] & ~(1u << (i % 8))) |
                                                           (out << (i % 8)));
                    }
                }
            }
            for (size_t z = 0; z < detail::KECCAK_W; ++z) {
                const size_t i = detail::keccak_bit_index(0, 0, z);
                want[i / 8] ^= static_cast<uint8_t>(((detail::KP800_RC[r] >> z) & 1) << (i % 8));
            }
            EXPECT_EQ(from_plain(chi_s), want);
        }
    }
}

// The lane-based round of keccak.cpp is R = iota o chi o L', where L' (theta, rho, pi on lanes) is
// GF(2)-linear (only XORs and rotations) and chi and iota are as in the circuit. Given
// ChiInverseExhaustive, chi^-1 (R (v)) = L' (v), so checking L' = L on the zero state and every
// unit vector proves that every lane-based round equals qs_keccak_round.
TEST(Keccak, RoundMatchesLanesOnBasis) {
    using namespace keccak::detail;
    for (size_t r = 0; r < KP800_ROUNDS; ++r) {
        for (size_t i = 0; i <= KP800_STATE_BITS; ++i) {
            const Kp800State v = i < KP800_STATE_BITS ? unit_state(i) : Kp800State{};
            Kp800State out = v;
            keccak_p800_rounds(out, r, 1);
            const auto lin = qs_keccak_iota_chi_inverse<PlainQS, 1>(to_plain(out), r);
            ASSERT_EQ(from_plain(lin), from_plain(detail::keccak_theta_rho_pi(to_plain(v))))
                << "round " << r << ", unit vector " << i;
        }
    }
}

namespace {

// Witness for qs_keccak on a secret input: the input state (bytes 0 .. 100), followed by the
// committed intermediate states.
constexpr size_t SEG_WIT_OFF_STATES = KP800_STATE_BYTES;
using SegWitness = std::array<uint8_t, SEG_WIT_OFF_STATES + keccak::detail::COMMITTED_STATES_BYTES>;

constexpr keccak::detail::InputMap IDENTITY_MAP = [] {
    keccak::detail::InputMap map{};
    for (size_t i = 0; i < KP800_STATE_BYTES; ++i) {
        map[i] = static_cast<int>(i);
    }
    return map;
}();
static_assert(keccak::detail::input_map_is_valid(IDENTITY_MAP, 0, KP800_STATE_BYTES));

SegWitness honest_seg_witness(const Kp800State& input) {
    SegWitness w{};
    std::ranges::copy(input, w.begin());
    keccak::detail::encode_committed_states(
        std::span(w).subspan<SEG_WIT_OFF_STATES, keccak::detail::COMMITTED_STATES_BYTES>(), input);
    return w;
}

struct SegResult {
    Kp800State out;
    std::vector<bool> violated;
};

SegResult run_qs_keccak(const SegWitness& w) {
    PlainQS qs{w.data(), {}};
    const auto out = keccak::detail::qs_keccak(
        &qs, keccak::detail::qs_input(&qs, Kp800State{}, IDENTITY_MAP), SEG_WIT_OFF_STATES);
    return {from_plain(out), qs.violated};
}

} // namespace

// The segment constraints hold for the honest intermediate states, and then the output of qs_keccak
// is the permutation of the input.
TEST(Keccak, SegmentsAcceptTrueTrace) {
    std::mt19937_64 rng(0x5e9);
    for (size_t n = 0; n < 20; ++n) {
        const Kp800State input = n == 0 ? Kp800State{} : random_state(rng);
        const auto r = run_qs_keccak(honest_seg_witness(input));
        EXPECT_EQ(r.violated.size(), keccak::detail::NUM_SEGMENT_CONSTRAINTS);
        EXPECT_EQ(std::ranges::count(r.violated, true), 0);
        EXPECT_EQ(to_hex(r.out), to_hex(keccak_p800(input)));
    }
}

// The backward side of each segment, qs_keccak_rounds_inverse_partial, inverts the rounds it
// undoes: applying chi and iota of the first undone round and then the remaining rounds forward
// recovers the committed state. Hence it's injective, so for a given previous state, the
// constraints of a segment have exactly one solution, the true round output. (That this holds for
// all states follows from LinearLayerInverseOnBasis and ChiInverseExhaustive; this tests the
// composition as instantiated by the segments.)
TEST(Keccak, SegmentBackwardSideIsInjective) {
    using namespace keccak::detail;
    std::mt19937_64 rng(0xbac);
    const auto check = [](const Kp800State& s, auto k_const) {
        constexpr size_t k = decltype(k_const)::value;
        constexpr Segment seg = SEGMENTS[k];
        const size_t meet = SEGMENT_START[k] + seg.forward; // first undone round
        const auto bwd = qs_keccak_rounds_inverse_partial<PlainQS, seg.backward>(
            to_plain(s), SEGMENT_START[k + 1]);
        Kp800State fwd = from_plain(qs_keccak_round<PlainQS, ipow(3, seg.backward)>(
            detail::keccak_theta_rho_pi_inverse(bwd), meet));
        keccak_p800_rounds(fwd, meet + 1, seg.backward - 1);
        EXPECT_EQ(to_hex(fwd), to_hex(s)) << "segment " << k;
    };
    for (size_t n = 0; n < 50; ++n) {
        const Kp800State s = n < 32 ? row_state(n) : random_state(rng);
        check(s, std::integral_constant<size_t, 0>());
        check(s, std::integral_constant<size_t, 1>());
    }
}

// A committed state other than the true one violates a constraint of its own segment. Random
// states, and states at Hamming distance 1 and 2 from the true one.
TEST(Keccak, SegmentsRejectWrongStates) {
    using namespace keccak::detail;
    std::mt19937_64 rng(0x0dd);
    const Kp800State input = random_state(rng);
    const SegWitness honest = honest_seg_witness(input);
    for (size_t k = 0; k < NUM_COMMITTED_STATES; ++k) {
        const size_t off = SEG_WIT_OFF_STATES + k * KP800_STATE_BYTES;
        const auto violated_in_segment = [k](const std::vector<bool>& v) {
            return std::any_of(v.begin() + static_cast<std::ptrdiff_t>(k * KP800_STATE_BITS),
                               v.begin() + static_cast<std::ptrdiff_t>((k + 1) * KP800_STATE_BITS),
                               [](bool b) { return b; });
        };
        for (size_t n = 0; n < 50; ++n) {
            SegWitness w = honest;
            for (size_t i = 0; i < KP800_STATE_BYTES; ++i) {
                w[off + i] = static_cast<uint8_t>(rng());
            }
            EXPECT_TRUE(violated_in_segment(run_qs_keccak(w).violated)) << "segment " << k;
        }
        for (size_t n = 0; n < 200; ++n) {
            SegWitness w = honest;
            const size_t i = rng() % KP800_STATE_BITS, j = rng() % KP800_STATE_BITS;
            w[off + i / 8] ^= static_cast<uint8_t>(1u << (i % 8));
            if (n % 2) {
                w[off + j / 8] ^= static_cast<uint8_t>(1u << (j % 8));
            }
            if (w == honest) {
                continue;
            }
            EXPECT_TRUE(violated_in_segment(run_qs_keccak(w).violated))
                << "segment " << k << ", bits " << i << ", " << j;
        }
    }
}

// qs_input places witness bytes and public bytes as given by the map, bit i of the state being
// bit i % 8 of byte i / 8.
TEST(Keccak, InputPlacesBytes) {
    keccak::detail::InputMap map;
    map.fill(-1);
    map[3] = 0;
    map[99] = 1;
    const std::array<uint8_t, 2> w = {0xa5, 0x3c};
    Kp800State pub;
    for (size_t i = 0; i < pub.size(); ++i) {
        pub[i] = static_cast<uint8_t>(17 * i + 1);
    }
    PlainQS qs{w.data(), {}};
    Kp800State want = pub;
    want[3] = 0xa5;
    want[99] = 0x3c;
    EXPECT_EQ(from_plain(keccak::detail::qs_input(&qs, pub, map)), want);
    EXPECT_TRUE(qs.violated.empty());
}

// qs_byte is an injective map from bytes to GF(2^128), and agrees with the embedding of witness
// bytes (load_witness_8_bits_and_combine), so comparing output bytes in GF(2^128) compares bytes.
TEST(Keccak, ByteEmbeddingIsInjective) {
    using poly = faest::poly_secpar<faest::secpar::s128>;
    std::vector<poly> seen;
    for (unsigned b = 0; b < 256; ++b) {
        Kp800State s{};
        s[5] = static_cast<uint8_t>(b);
        const auto e = keccak::detail::qs_byte(to_plain(s), 5).v;
        const std::array<uint8_t, 1> wb = {static_cast<uint8_t>(b)};
        const PlainQS qs{wb.data(), {}};
        EXPECT_TRUE(e == qs.load_witness_8_bits_and_combine(0).v) << "byte " << b;
        for (const poly& p : seen) {
            EXPECT_FALSE(e == p) << "byte " << b;
        }
        seen.push_back(e);
    }
}
