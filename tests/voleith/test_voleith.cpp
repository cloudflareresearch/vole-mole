template <typename R = FaestRelation> typename R::instance kat_instance() {
    typename R::instance x{};
    x.pk_packed = PK;
    faest::faest_unpack_public_key<typename R::params>(&x.pk, PK.data());
    x.msg.assign(MSG.begin(), MSG.end());
    return x;
}

