// Evaluate the PRG on a plaintext key.
template <size_t KEY_BITS, size_t NUM_OUTPUTS>
std::array<uint8_t, NUM_OUTPUTS / 8> plain_eval(const PublicMap<KEY_BITS, NUM_OUTPUTS>& map,
                                                std::span<const uint8_t, KEY_BITS / 8> key) {
    std::array<uint8_t, NUM_OUTPUTS / 8> out;
    eval(map, key, std::span(out));
    return out;
}

// Check one known answer for the PRG with the given parameters.
template <size_t KEY_BITS, size_t NUM_OUTPUTS>
void check_known_answer(const std::vector<uint8_t>& dst, const std::vector<uint8_t>& key,
                        const std::string& matrix1, const std::string& output) {
    ASSERT_EQ(key.size(), KEY_BITS / 8);
    const PublicMap<KEY_BITS, NUM_OUTPUTS> map(dst);
    auto m = std::make_unique<typename PublicMap<KEY_BITS, NUM_OUTPUTS>::Matrix>();
    map.matrix(1, *m);
    EXPECT_EQ(to_hex(std::span(*m).first(32)), matrix1);
    EXPECT_EQ(
        to_hex(plain_eval(map, std::span<const uint8_t, KEY_BITS / 8>(key.data(), KEY_BITS / 8))),
        output);
}

