// Known answers generated by the reference implementation, tools/mq_ref.py.
TEST(MqPrg, KnownAnswers) {
    std::ifstream in(std::string(VOLE_MOLE_TEST_DATA_DIR) + "/mq/kat.txt");
    ASSERT_TRUE(in.is_open()) << "can't open mq/kat.txt";
    size_t count = 0;
    std::string label, dst_hex, key_hex, matrix1, output;
    size_t n = 0, num_outputs = 0;
    while (in >> std::ws && in.peek() != std::char_traits<char>::eof()) {
        if (in.peek() == '#') {
            std::string comment;
            std::getline(in, comment);
            continue;
        }
        ASSERT_TRUE(in >> label >> dst_hex && label == "dst");
        ASSERT_TRUE(in >> label >> n && label == "n");
        ASSERT_TRUE(in >> label >> num_outputs && label == "N");
        ASSERT_TRUE(in >> label >> key_hex && label == "key");
        ASSERT_TRUE(in >> label >> matrix1 && label == "matrix1");
        ASSERT_TRUE(in >> label >> output && label == "output");
        SCOPED_TRACE("known answer " + std::to_string(count));
        const auto dst = hex_decode(dst_hex);
        const auto key = hex_decode(key_hex);
        ASSERT_TRUE(dst && key);
        if (n == 144 && num_outputs == 128) {
            check_known_answer<144, 128>(*dst, *key, matrix1, output);
        } else if (n == 160 && num_outputs == 64) {
            check_known_answer<160, 64>(*dst, *key, matrix1, output);
        } else if (n == 136 && num_outputs == 64) {
            check_known_answer<136, 64>(*dst, *key, matrix1, output);
        } else {
            FAIL() << "no instantiation for n = " << n << ", N = " << num_outputs;
        }
        ++count;
    }
    EXPECT_EQ(count, 4u);
}

TEST(MqPrg, KeyBits) {
    // The table is sorted, and the key length grows with the number of outputs.
    for (size_t i = 1; i < KEY_BITS_TABLE.size(); ++i) {
        EXPECT_LT(KEY_BITS_TABLE[i - 1].key_bits, KEY_BITS_TABLE[i].key_bits);
        EXPECT_LT(KEY_BITS_TABLE[i - 1].max_outputs, KEY_BITS_TABLE[i].max_outputs);
    }
    for (const auto& e : KEY_BITS_TABLE) {
        EXPECT_EQ(e.key_bits % 16, 0u);
        EXPECT_GE(e.key_bits, 128u);
        EXPECT_GT(e.max_outputs, e.key_bits); // it's a PRG
    }
    static_assert(key_bits(1) == 144);
    static_assert(key_bits(190) == 144 && key_bits(191) == 160);
    static_assert(key_bits(2048) == 336);
    static_assert(key_bits(2744) == 384);
    EXPECT_THROW((void)key_bits(KEY_BITS_TABLE.back().max_outputs + 1), std::invalid_argument);
}

TEST(MqPrg, DependsOnDstAndKey) {
    constexpr size_t KEY_BITS = 160, NUM_OUTPUTS = 64;
    const PublicMap<KEY_BITS, NUM_OUTPUTS> a(filled<7>(0));
    const PublicMap<KEY_BITS, NUM_OUTPUTS> b(filled<7>(1));
    const auto key = filled<KEY_BITS / 8>(0x30);
    auto other_key = key;
    other_key[KEY_BITS / 8 - 1] ^= 0x80;
    EXPECT_NE(plain_eval(a, std::span(key)), plain_eval(b, std::span(key)));
    EXPECT_NE(plain_eval(a, std::span(key)), plain_eval(a, std::span(other_key)));
    // G(0) = 0, since there is no constant term.
    const std::array<uint8_t, KEY_BITS / 8> zero{};
    EXPECT_EQ(plain_eval(a, std::span(zero)), (std::array<uint8_t, NUM_OUTPUTS / 8>{}));
}

// The outputs are about balanced.
TEST(MqPrg, OutputsAreBalanced) {
    constexpr size_t KEY_BITS = 336, NUM_OUTPUTS = 2048;
    const PublicMap<KEY_BITS, NUM_OUTPUTS> map(filled<7>(0x11));
    const auto key = filled<KEY_BITS / 8>(0x42);
    const auto out = plain_eval(map, std::span(key));
    size_t ones = 0;
    for (const uint8_t b : out) {
        ones += static_cast<size_t>(std::popcount(b));
    }
    EXPECT_GT(ones, NUM_OUTPUTS / 2 - 150);
    EXPECT_LT(ones, NUM_OUTPUTS / 2 + 150);
}

// Evaluating on committed values computes e + G(K).
template <size_t KEY_BITS, size_t NUM_OUTPUTS> void check_committed_evaluation() {
    using qs_1 = faest::quicksilver_gf2<PlainQS, 1>;
    const PublicMap<KEY_BITS, NUM_OUTPUTS> map(filled<7>(0x22));

    for (const uint8_t start : {uint8_t{0x00}, uint8_t{0x9c}}) {
        const auto key = filled<KEY_BITS / 8>(start);
        const auto e = filled<NUM_OUTPUTS / 8>(static_cast<uint8_t>(start + 0x37));

        std::vector<qs_1> committed;
        for (size_t i = 0; i < KEY_BITS; ++i) {
            committed.emplace_back(((key[i / 8] >> (i % 8)) & 1) != 0);
        }
        const auto w =
            qs_eval<PlainQS>(map, std::span<const qs_1, KEY_BITS>(committed), std::span(e));
        ASSERT_EQ(w.size(), NUM_OUTPUTS);

        auto expected = plain_eval(map, std::span(key));
        for (size_t i = 0; i < expected.size(); ++i) {
            expected[i] ^= e[i];
        }
        for (size_t i = 0; i < NUM_OUTPUTS; ++i) {
            const bool bit = ((expected[i / 8] >> (i % 8)) & 1) != 0;
            EXPECT_EQ(w[i].v, bit) << "output " << i;
        }
    }
}

TEST(MqPrg, CommittedEvaluationMatchesPlaintext) {
    check_committed_evaluation<336, 2048>();
    check_committed_evaluation<136, 64>(); // key length not a multiple of 16
}

