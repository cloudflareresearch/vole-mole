// Instances of the same size have different public maps (their DSTs differ by the index).
TEST(MqSplit, InstancesDiffer) {
    using Map = SplitMap<2048, 2>;
    static_assert(std::is_same_v<Map::InstanceMap<0>, Map::InstanceMap<1>>);
    const Map map(filled<5>(0x44));
    auto m0 = std::make_unique<Map::InstanceMap<0>::Matrix>();
    auto m1 = std::make_unique<Map::InstanceMap<1>::Matrix>();
    map.instance<0>().matrix(0, *m0);
    map.instance<1>().matrix(0, *m1);
    EXPECT_NE(*m0, *m1);
    // And instance 0 is the PRG with DST dst || le32(0).
    const Map::InstanceMap<0> direct(
        std::vector<uint8_t>{0x44, 0x45, 0x46, 0x47, 0x48, 0, 0, 0, 0});
    auto md = std::make_unique<Map::InstanceMap<0>::Matrix>();
    direct.matrix(0, *md);
    EXPECT_EQ(*m0, *md);
}

