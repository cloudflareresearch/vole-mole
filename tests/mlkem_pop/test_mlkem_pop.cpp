namespace {

constexpr std::string_view CONTEXT_STR = "CSR challenge 1234";
const std::span<const uint8_t> CONTEXT(reinterpret_cast<const uint8_t*>(CONTEXT_STR.data()),
                                       CONTEXT_STR.size());
const ProveSeed RHO = filled<PROVE_SEED_BYTES>(0x50);

template <ParamSet P> const KeyPair<P>& key_pair() {
    static const KeyPair<P> kp = keygen<P>(filled<SEED_BYTES>(0x00));
    return kp;
}

// The witness s = NTT^-1(s-hat) of a decapsulation key.
template <ParamSet P> std::vector<Fq> witness_of(const DecapsKey<P>& dk) {
    std::vector<Fq> s(PopRelation<P>::WITNESS_LEN);
    for (size_t i = 0; i < P::K; ++i) {
        const auto s_i = std::span(s).subspan(i * 256).template first<256>();
        EXPECT_TRUE(
            mlkem::detail::decode12(std::span(dk).subspan(384 * i).template first<384>(), s_i));
        mlkem::detail::inv_ntt(s_i);
    }
    return s;
}

template <ParamSet P>
Proof<P> prove_raw(const EncapsKey<P>& ek, const std::vector<Fq>& s,
                   std::span<const uint8_t> context = CONTEXT) {
    return prove_unchecked<P>(ek, std::span<const Fq, PopRelation<P>::WITNESS_LEN>(s), context,
                              RHO);
}

template <typename P> class MlKemPopTest : public ::testing::Test {};
using ParamSets = ::testing::Types<MlKem512, MlKem768, MlKem1024>;
TYPED_TEST_SUITE(MlKemPopTest, ParamSets);

} // namespace

TYPED_TEST(MlKemPopTest, ProofSize) {
    using P = TypeParam;
    EXPECT_EQ(mlkem_pop::PROOF_BYTES<P>, Layout<PopRelation<P>>::PROOF_BYTES);
}

TYPED_TEST(MlKemPopTest, Verifies) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = mlkem_pop::prove<P>(dk, CONTEXT);
    EXPECT_TRUE(mlkem_pop::verify<P>(ek, CONTEXT, proof));
}

TYPED_TEST(MlKemPopTest, VerifiesFreshKeys) {
    using P = TypeParam;
    for (int i = 0; i < 3; ++i) {
        const auto [ek, dk] = keygen<P>();
        EXPECT_TRUE(mlkem_pop::verify<P>(ek, {}, mlkem_pop::prove<P>(dk, {})));
    }
}

