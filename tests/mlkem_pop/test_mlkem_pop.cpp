TYPED_TEST(MlKemPopTest, KnownAnswer) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = prove_with_seed<P>(dk, CONTEXT, RHO);
    EXPECT_EQ(vole_mole::test::to_hex(mlkem::detail::hash_h(proof)), proof_digest<P>());
    EXPECT_TRUE(mlkem_pop::verify<P>(ek, CONTEXT, proof));
}

TYPED_TEST(MlKemPopTest, IsDeterministicInRho) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = prove_with_seed<P>(dk, CONTEXT, RHO);
    EXPECT_EQ(proof, prove_with_seed<P>(dk, CONTEXT, RHO));
    auto rho2 = RHO;
    rho2[0] ^= 1;
    const auto proof2 = prove_with_seed<P>(dk, CONTEXT, rho2);
    EXPECT_NE(proof, proof2);
    EXPECT_TRUE(mlkem_pop::verify<P>(ek, CONTEXT, proof2));

    // prove_unchecked with the honest witness computes the same proof.
    EXPECT_EQ(proof, prove_raw<P>(ek, witness_of<P>(dk)));
}

TYPED_TEST(MlKemPopTest, RejectsWrongContext) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = mlkem_pop::prove<P>(dk, CONTEXT);
    constexpr std::string_view other = "CSR challenge 1235";
    EXPECT_FALSE(mlkem_pop::verify<P>(
        ek, std::span(reinterpret_cast<const uint8_t*>(other.data()), other.size()), proof));
    EXPECT_FALSE(mlkem_pop::verify<P>(ek, {}, proof));
}

TYPED_TEST(MlKemPopTest, RejectsWrongKey) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = mlkem_pop::prove<P>(dk, CONTEXT);
    const auto other = keygen<P>(filled<SEED_BYTES>(0x01));
    EXPECT_FALSE(mlkem_pop::verify<P>(other.ek, CONTEXT, proof));

    // Change one coefficient of t-hat (keeping it canonical).
    auto ek2 = ek;
    ek2[0] ^= 1;
    ASSERT_TRUE(mlkem::detail::parse_encaps_key<P>(ek2).has_value());
    EXPECT_FALSE(mlkem_pop::verify<P>(ek2, CONTEXT, proof));

    // Change rho.
    auto ek3 = ek;
    ek3.back() ^= 1;
    EXPECT_FALSE(mlkem_pop::verify<P>(ek3, CONTEXT, proof));
}

TYPED_TEST(MlKemPopTest, RejectsEncapsKeyFailingModulusCheck) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = mlkem_pop::prove<P>(dk, CONTEXT);
    auto bad = ek;
    bad[0] = 0xff;
    bad[1] |= 0x0f; // first coefficient = 4095
    EXPECT_FALSE(mlkem_pop::verify<P>(bad, CONTEXT, proof));
}

TYPED_TEST(MlKemPopTest, RejectsTamperedProof) {
    using P = TypeParam;
    using Lay = Layout<PopRelation<P>>;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = prove_with_seed<P>(dk, CONTEXT, RHO);
    for (const size_t off :
         {Lay::OFF_IV, Lay::OFF_CORR, Lay::OFF_UTILDE, Lay::OFF_D, Lay::OFF_D + Lay::D_BYTES - 1,
          Lay::OFF_QS, Lay::OFF_DELTA, Lay::OFF_OPEN, Lay::PROOF_BYTES - 1}) {
        auto bad = proof;
        bad[off] ^= 0x10;
        EXPECT_FALSE(mlkem_pop::verify<P>(ek, CONTEXT, bad)) << "offset " << off;
    }
}

// Each F_q element of the proof has a unique encoding: replacing an element v by the 12-bit
// non-canonical encoding of the same value, v + q, makes the proof invalid.
TYPED_TEST(MlKemPopTest, RejectsNonCanonicalProof) {
    using P = TypeParam;
    using Lay = Layout<PopRelation<P>>;
    const auto& [ek, dk] = key_pair<P>();
    const auto proof = prove_with_seed<P>(dk, CONTEXT, RHO);
    for (const auto [off, len] :
         {std::pair{Lay::OFF_CORR, Lay::CORR_BYTES}, std::pair{Lay::OFF_UTILDE, Lay::UTILDE_BYTES},
          std::pair{Lay::OFF_D, Lay::D_BYTES}, std::pair{Lay::OFF_QS, Lay::QS_BYTES}}) {
        // The first element of the section (the low half of a packed pair) with v + q < 2^12.
        bool found = false;
        for (size_t i = off; i + 3 <= off + len; i += 3) {
            const uint32_t v = proof[i] | ((proof[i + 1] & 0xfu) << 8);
            if (v + Q < 4096) {
                auto bad = proof;
                const uint32_t w = v + Q;
                bad[i] = static_cast<uint8_t>(w);
                bad[i + 1] = static_cast<uint8_t>((bad[i + 1] & 0xf0) | (w >> 8));
                EXPECT_FALSE(mlkem_pop::verify<P>(ek, CONTEXT, bad)) << "offset " << i;
                found = true;
                break;
            }
        }
        EXPECT_TRUE(found) << "section at " << off;
    }
}

// The prover refuses invalid decapsulation keys.
TYPED_TEST(MlKemPopTest, ProverRejectsInvalidDecapsKey) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    using Parts = mlkem::detail::DecapsKeyParts<P>;

    auto bad_hash = dk;
    bad_hash[Parts::OFF_H] ^= 1;
    EXPECT_THROW(mlkem_pop::prove<P>(bad_hash, CONTEXT), std::invalid_argument);

    // A different s-hat: the secret is no longer short (with overwhelming probability).
    auto bad_secret = dk;
    bad_secret[0] ^= 1;
    EXPECT_THROW(mlkem_pop::prove<P>(bad_secret, CONTEXT), std::invalid_argument);

    // s-hat fails the modulus check: its first coefficient is 4095.
    auto bad_modulus = dk;
    bad_modulus[Parts::OFF_S_HAT] = 0xff;
    bad_modulus[Parts::OFF_S_HAT + 1] |= 0x0f;
    EXPECT_THROW(mlkem_pop::prove<P>(bad_modulus, CONTEXT), std::invalid_argument);

    // The z part isn't covered by the statement.
    auto other_z = dk;
    other_z[Parts::OFF_Z] ^= 1;
    EXPECT_TRUE(mlkem_pop::verify<P>(ek, CONTEXT, mlkem_pop::prove<P>(other_z, CONTEXT)));
}

// Soundness: a prover who doesn't know a short (s, e) for ek can't produce a valid proof, even by
// running the honest prover on its best guess.
TYPED_TEST(MlKemPopTest, CheatingProversFail) {
    using P = TypeParam;
    const auto& [ek, dk] = key_pair<P>();
    const auto s = witness_of<P>(dk);
    ASSERT_TRUE(mlkem_pop::verify<P>(ek, CONTEXT, prove_raw<P>(ek, s)));

    // A short s that isn't the secret, e.g., the secret of another key: e is then long.
    const auto other = keygen<P>(filled<SEED_BYTES>(0x02));
    EXPECT_FALSE(mlkem_pop::verify<P>(ek, CONTEXT, prove_raw<P>(ek, witness_of<P>(other.dk))));

    // The secret with one coefficient out of range by one (so e changes, too).
    auto s1 = s;
    s1[7] = fq_add(s1[7], 1);
    EXPECT_FALSE(mlkem_pop::verify<P>(ek, CONTEXT, prove_raw<P>(ek, s1)));

    // The all-zero s: then e = NTT^-1(t-hat), which is long.
    EXPECT_FALSE(mlkem_pop::verify<P>(
        ek, CONTEXT, prove_raw<P>(ek, std::vector<Fq>(PopRelation<P>::WITNESS_LEN, 0))));

    // For t-hat = NTT(e) with e short, s = 0 is a valid witness: this exercises the e range check
    // on its own. Then e with a coefficient eta + 1 must be rejected.
    for (const int32_t e0 : {int32_t{P::ETA1}, int32_t{P::ETA1} + 1}) {
        EncapsKey<P> ek_e = ek;
        mlkem::detail::Poly e{};
        e[0] = fq_from_int(-e0);
        mlkem::detail::ntt(e);
        mlkem::detail::encode12(e, std::span(ek_e).template first<384>());
        for (size_t i = 1; i < P::K; ++i) {
            const mlkem::detail::Poly zero{};
            mlkem::detail::encode12(zero, std::span(ek_e).subspan(384 * i).template first<384>());
        }
        const auto proof = prove_raw<P>(ek_e, std::vector<Fq>(PopRelation<P>::WITNESS_LEN, 0));
        EXPECT_EQ(mlkem_pop::verify<P>(ek_e, CONTEXT, proof), e0 <= int32_t{P::ETA1}) << e0;
    }
}

// The range polynomial vanishes exactly on [-eta, eta].
TYPED_TEST(MlKemPopTest, RangePolynomial) {
    using P = TypeParam;
    constexpr auto f = vole_mole::mlkem_pop::detail::range_poly<P::ETA1>();
    for (uint32_t x = 0; x < Q; ++x) {
        uint32_t acc = 0;
        for (size_t i = f.size(); i-- > 0;) {
            acc = (acc * x + f[i]) % Q;
        }
        const int32_t c = vole_mole::voleith_fq::detail::fq_centered(static_cast<Fq>(x));
        EXPECT_EQ(acc == 0, -int32_t{P::ETA1} <= c && c <= int32_t{P::ETA1}) << x;
    }
}
